async function writeMerged(ns: "navigation" | "pages", locale: string, overlay: Dict) {
  const en = JSON.parse(await readFile(path.join(root, "en", `${ns}.json`), "utf8")) as Dict;
  const merged = { ...en, ...overlay };
  await mkdir(path.join(root, locale), { recursive: true });
  await writeFile(
    path.join(root, locale, `${ns}.json`),
    `${JSON.stringify(merged, null, 2)}\n`,
    "utf8",
  );
}

async function main() {
  for (const locale of locales) {
    await writeMerged("navigation", locale, navigation[locale]);
    await writeMerged("pages", locale, pages[locale]);
  }
  console.log("Wrote navigation + pages for", locales.join(", "));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
