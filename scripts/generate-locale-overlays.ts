async function main() {
  for (const locale of locales) {
    await mkdir(path.join(root, locale), { recursive: true });
    for (const ns of namespaces) {
      const en = JSON.parse(await readFile(path.join(root, "en", `${ns}.json`), "utf8")) as Record<
        string,
        string
      >;
      const overlay = overlays[ns]?.[locale] || {};
      const merged = { ...en, ...overlay };
      if (ns === "common") merged.appName = "VedaMilan AI";
      await writeFile(
        path.join(root, locale, `${ns}.json`),
        `${JSON.stringify(merged, null, 2)}\n`,
        "utf8",
      );
    }
  }
  console.log(`Generated overlays for ${locales.join(", ")}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
