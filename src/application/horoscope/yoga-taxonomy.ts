export function getYogaCatalogEntry(id: string): YogaCatalogEntry | undefined {
  return YOGA_TAXONOMY.find((e) => e.id === id);
}

export function getYogasByCategory(category: YogaCategoryId): YogaCatalogEntry[] {
  return YOGA_TAXONOMY.filter((e) => e.category === category);
}

export function getImplementedYogas(): YogaCatalogEntry[] {
  return YOGA_TAXONOMY.filter(
    (e) => e.implementationStatus === "implemented" && e.calculationSupported,
  );
}

export function getPlannedYogas(): YogaCatalogEntry[] {
  return YOGA_TAXONOMY.filter(
    (e) => e.implementationStatus === "planned" || e.implementationStatus === "partial",
  );
}

export function getNotImplementedYogas(): YogaCatalogEntry[] {
  return YOGA_TAXONOMY.filter((e) => e.implementationStatus === "not_implemented");
}

export function getYogaCategories(): YogaCategoryId[] {
  return [...new Set(YOGA_TAXONOMY.map((e) => e.category))];
}

export function getYogaCategoryLabel(category: YogaCategoryId): string {
  const labels: Record<YogaCategoryId, string> = {
    raja: "Raja Yoga",
    dhana: "Dhana Yoga",
    solar: "Solar Yoga",
    lunar: "Lunar Yoga",
    mahapurusha: "Pancha Mahapurusha",
    nabhasa: "Nabhasa Yoga",
    planetary: "Planetary Yoga",
    jaimini: "Jaimini Yoga",
    nakshatra: "Nakshatra Yoga",
    other: "Other Classical Yogas",
  };
  return labels[category];
}
